    "### IEC 62619 - Requisitos de Seguridad para Baterias Industriales\n\n"
    "**Alcance:** Requisitos de seguridad para celdas y baterias secundarias de litio utilizadas en aplicaciones "
    "industriales, incluyendo BESS.\n\n"
    "**Requisitos clave:**\n"
