    "- Medicion de emisiones de gas durante la fuga termica\n"
    "- Evaluacion de calor radiante y temperaturas de llama\n"
    "- Evaluacion de propagacion de incendios mas alla del contenedor\n\n"
    "**Donde se requiere:** America del Norte (requerido por NFPA 855 y la mayoria de los codigos de bomberos). "
